/// Gospel verses for the student dashboard (365-day annual cycle).
///
/// Every entry is taken from one of the four Gospels (Matthew, Mark, Luke or
/// John). Full authentic Amharic text is included for every day of the year,
/// accompanied by English references for locale compatibility.
library;

enum GospelBook {
  matthew('ማቴዎስ', 'Matthew'),
  mark('ማርቆስ', 'Mark'),
  luke('ሉቃስ', 'Luke'),
  john('ዮሐንስ', 'John');

  const GospelBook(this.amharicName, this.englishName);

  final String amharicName;
  final String englishName;

  String name(bool isAmharic) => isAmharic ? amharicName : englishName;
}

class GospelVerse {
  const GospelVerse({
    required this.book,
    required this.chapter,
    required this.verses,
    required this.amharic,
    this.english = '',
  });

  final GospelBook book;
  final int chapter;

  /// Verse number or range, for example `16` or `29-30`.
  final String verses;

  final String amharic;
  final String english;

  String get referenceAm => '${book.amharicName} $chapter:$verses';
  String get referenceEn => '${book.englishName} $chapter:$verses';

  String reference([bool isAmharic = true]) => isAmharic ? referenceAm : referenceEn;

  String text([bool isAmharic = true]) => isAmharic ? amharic : (english.isNotEmpty ? english : amharic);
}

